function applyLanguage(lang){
  if(!translations[lang]) lang = 'ar';
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  const dict = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const key = el.getAttribute('data-i18n-html');
    if(dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    if(dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });

  document.querySelectorAll('.lang-switch button').forEach(btn=>{
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  try{ localStorage.setItem('nawa-lang', lang); }catch(e){}

  if(window.onLanguageApplied) window.onLanguageApplied(lang);
}

(function initLang(){
  let saved = null;
  try{ saved = localStorage.getItem('nawa-lang'); }catch(e){}
  const lang = saved || 'ar';
  document.addEventListener('DOMContentLoaded', ()=> applyLanguage(lang));
})();
